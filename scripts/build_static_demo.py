"""Precompute the static GitHub Pages demo snapshot (fixture mode, SYNTHETIC).

The Pages site has no backend, so every answer it can show is computed here, ahead of time, by the *same*
pipeline the API serves (`app.pipeline.answer_query`) in fixture mode — SYNTHETIC documents from
`data/fixtures/`, replayed extraction, no network, no keys. Nothing is hand-written.

Areas: the 50 postcode areas of the committed sweep (`runs/sweep_summary.json`) plus the two areas the demo
video uses that the evenly spaced sweep sample does not contain (5612 Eindhoven, 3011 Rotterdam). Each area
is answered in both directions at one fixed power (60 kW, the SPEC §1 persona — the sweep's power).

Output (default `frontend/public/demo/`, gitignored, regenerated by `make build-pages`):

    answers/<pc4>.<direction>.json   one QueryResponse per area and direction (schema-validated)
    index.json                       what is in the snapshot (areas, verdicts, provenance)
    ab_experiment_results.json       copy of runs/ab_experiment_results.json
    sweep_summary.json               copy of runs/sweep_summary.json

Run:  uv run --project backend python scripts/build_static_demo.py   (or: make build-pages)
"""

from __future__ import annotations

import argparse
import asyncio
import copy
import json
import shutil
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT / "backend") not in sys.path:  # allow running without an installed package
    sys.path.insert(0, str(REPO_ROOT / "backend"))

from app.pipeline import Services, answer_query  # noqa: E402
from app.stages.s1_resolve_location import resolve  # noqa: E402
from app.stages.s3_extract import ReplayExtractor  # noqa: E402

SNAPSHOT_ID = "static-demo-v1"
POWER_KW = 60.0  # the SPEC §1 persona's PV system; the sweep ran at the same power
DIRECTIONS = ("feed_in", "consumption")
DEFAULT_OUT = REPO_ROOT / "frontend" / "public" / "demo"
SWEEP_PATH = REPO_ROOT / "runs" / "sweep_summary.json"
AB_PATH = REPO_ROOT / "runs" / "ab_experiment_results.json"
SCHEMA_PATH = REPO_ROOT / "schemas" / "core-schemas.json"

# Areas the demo video (video/script.md S03-S06) needs that the systematic sweep sample skips.
EXTRA_AREAS: tuple[tuple[str, str], ...] = (
    ("5612", "demo video S03-S05 (Eindhoven, 5612 AB)"),
    ("3011", "demo video S06 (Rotterdam, refusal)"),
)


def _validator() -> Any:
    import jsonschema

    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    schema = copy.deepcopy(schema)
    schema["$ref"] = "#/$defs/QueryResponse"
    return jsonschema.Draft202012Validator(schema, format_checker=jsonschema.FormatChecker())


def select_areas(sweep: dict[str, Any]) -> list[dict[str, Any]]:
    """Sweep areas in sweep order, then the video extras (skipped if the sweep already has them)."""
    areas = [
        {
            "postcode4": a["postcode4"],
            "dso": a["dso"],
            "gemeente": a["gemeente"],
            "source": "sweep_sample",
            "note": None,
        }
        for a in sweep["areas"]
    ]
    seen = {a["postcode4"] for a in areas}
    for pc4, note in EXTRA_AREAS:
        if pc4 in seen:
            continue
        loc, _ = resolve(pc4)
        if not loc["resolved"]:
            raise SystemExit(f"extra area {pc4} does not resolve to a DSO: {loc['abstain_reason']}")
        areas.append(
            {"postcode4": pc4, "dso": loc["dso"], "gemeente": loc["gemeente"], "source": "video_demo", "note": note}
        )
    return areas


def _git_sha() -> str | None:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], cwd=REPO_ROOT, capture_output=True, text=True, check=True
        )
        return out.stdout.strip() or None
    except (OSError, subprocess.CalledProcessError):
        return None


async def build(out_dir: Path, *, sweep_path: Path = SWEEP_PATH, ab_path: Path = AB_PATH) -> dict[str, Any]:
    sweep = json.loads(sweep_path.read_text(encoding="utf-8"))
    areas = select_areas(sweep)
    services = Services(mode="fixture", tavily=None, extractor=ReplayExtractor())
    validate = _validator()

    if out_dir.exists():
        shutil.rmtree(out_dir)
    (out_dir / "answers").mkdir(parents=True)

    entries: list[dict[str, Any]] = []
    for area in areas:
        verdicts: dict[str, str] = {}
        for direction in DIRECTIONS:
            qr = await answer_query(
                postcode=area["postcode4"],
                power_kw=POWER_KW,
                direction=direction,  # type: ignore[arg-type]
                services=services,
                run_id=f"{SNAPSHOT_ID}-{area['postcode4']}-{direction}",
                runs_dir=None,
            )
            errors = sorted(validate.iter_errors(qr), key=lambda e: list(e.path))
            if errors:
                first = errors[0]
                where = f"{area['postcode4']} {direction}"
                raise SystemExit(f"{where}: QueryResponse invalid at {list(first.path)}: {first.message}")
            if not qr["retrieval"]["synthetic"]:
                raise SystemExit(f"{area['postcode4']} {direction}: expected a SYNTHETIC fixture answer")
            name = f"{area['postcode4']}.{direction}.json"
            body = json.dumps(qr, ensure_ascii=False, indent=1) + "\n"
            (out_dir / "answers" / name).write_text(body, encoding="utf-8")
            verdicts[direction] = qr["answer"]["per_direction"][0]["verdict"]
        entries.append({**area, "verdicts": verdicts})

    shutil.copyfile(ab_path, out_dir / "ab_experiment_results.json")
    shutil.copyfile(sweep_path, out_dir / "sweep_summary.json")

    index = {
        "snapshot_id": SNAPSHOT_ID,
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds").replace("+00:00", "Z"),
        "git_sha": _git_sha(),
        "mode": "fixture",
        "synthetic": True,
        "power_kw": POWER_KW,
        "directions": list(DIRECTIONS),
        "note": (
            "Static snapshot for the GitHub Pages demo. Every answer was computed ahead of time by the GridQueue "
            "pipeline in fixture mode from SYNTHETIC documents in data/fixtures/ — not official publications, "
            "and no live Tavily or model calls."
        ),
        "sources": {
            "sweep": sweep.get("report_id"),
            "ab": json.loads(ab_path.read_text(encoding="utf-8")).get("experiment_id"),
        },
        "areas": entries,
    }
    (out_dir / "index.json").write_text(json.dumps(index, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return index


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help=f"output directory (default {DEFAULT_OUT})")
    args = parser.parse_args(argv)
    index = asyncio.run(build(args.out))
    n = len(index["areas"])
    abstained = sum(1 for a in index["areas"] if "NO_OFFICIAL_POSITION_FOUND" in a["verdicts"].values())
    print(f"static demo: {n} areas x {len(DIRECTIONS)} directions = {n * len(DIRECTIONS)} answers -> {args.out}")
    print(f"  areas with a refusal (no official position): {abstained}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
